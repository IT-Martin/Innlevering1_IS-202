#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")"

if ! command -v dotnet >/dev/null 2>&1; then
    echo ".NET 10 SDK is required to run the app." >&2
    exit 1
fi

if ! command -v docker >/dev/null 2>&1 || ! docker info >/dev/null 2>&1; then
    echo "Docker Desktop must be installed and running to start the local MariaDB database." >&2
    exit 1
fi

if ! docker compose version >/dev/null 2>&1; then
    echo "Docker Compose is required to start the local MariaDB database." >&2
    exit 1
fi

requested_app_port=${APP_PORT:-}
app_port=${requested_app_port:-5062}
if [[ ! "$app_port" =~ ^[0-9]+$ ]] || ((app_port < 1 || app_port > 65535)); then
    echo "APP_PORT must be a port number between 1 and 65535." >&2
    exit 1
fi

if [[ -n "$requested_app_port" ]]; then
    if nc -z 127.0.0.1 "$app_port" >/dev/null 2>&1; then
        echo "Port $app_port is already in use." >&2
        exit 1
    fi
else
    while nc -z 127.0.0.1 "$app_port" >/dev/null 2>&1; do
        if ((app_port == 65535)); then
            echo "No available port found from 5062 through 65535." >&2
            exit 1
        fi
        ((app_port += 1))
    done
    if ((app_port != 5062)); then
        echo "Port 5062 is already in use; using port $app_port instead."
    fi
fi

db_env_file=.local-db.env
if [[ ! -s "$db_env_file" ]]; then
    if docker volume inspect reachout_local_database >/dev/null 2>&1; then
        echo "An existing database volume was found without its password file. Restore .local-db.env before continuing." >&2
        exit 1
    fi
    if ! command -v openssl >/dev/null 2>&1; then
        echo "OpenSSL is required to generate a local database password." >&2
        exit 1
    fi
    db_password=$(openssl rand -hex 32)
    (umask 077; printf 'LOCAL_MARIADB_ROOT_PASSWORD=%s\n' "$db_password" > "$db_env_file")
fi

chmod 600 "$db_env_file"
db_password=$(sed -n 's/^LOCAL_MARIADB_ROOT_PASSWORD=//p' "$db_env_file" | head -n 1)
if [[ ! "$db_password" =~ ^[[:xdigit:]]{64}$ ]]; then
    echo "$db_env_file must contain a valid LOCAL_MARIADB_ROOT_PASSWORD generated by this script." >&2
    exit 1
fi

docker compose --env-file "$db_env_file" up -d db
db_container=$(docker compose --env-file "$db_env_file" ps -q db)
if [[ -z "$db_container" ]]; then
    echo "Docker Compose did not create the local MariaDB container." >&2
    exit 1
fi
for ((attempt = 0; attempt < 60; attempt++)); do
    db_status=$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$db_container" 2>/dev/null || true)
    if [[ "$db_status" == healthy ]]; then
        break
    fi
    if [[ "$db_status" == unhealthy || "$db_status" == exited ]]; then
        echo "The local MariaDB container failed to start (status: $db_status)." >&2
        exit 1
    fi
    sleep 2
done

if [[ "$db_status" != healthy ]]; then
    echo "The local MariaDB database did not become ready in time." >&2
    exit 1
fi

ASPNETCORE_ENVIRONMENT=Development \
ASPNETCORE_URLS="http://localhost:$app_port" \
LocalPreview=true \
ConnectionStrings__DefaultConnection='Server=127.0.0.1;Port=3307;Database=resourcedb;User=root;Password=Password;' \
InitialAdmin__Email=admin@test.no \
InitialAdmin__Password=adminadminadmin \
InitialPublicActor__Email=offentlig@test.no \
InitialPublicActor__Password=offentligoffentligoffentlig \
    env ConnectionStrings__DefaultConnection="Server=127.0.0.1;Port=3307;Database=resourcedb;User=root;Password=${db_password};" \
        dotnet run --project Innlevering1_Gruppe2/Innlevering1_Gruppe2.csproj --no-launch-profile
